"""Conservative cleanup of generated backups/patch folders. Dry-run unless --apply.
No deletion: files are moved to archive directory outside project.
"""
from pathlib import Path
from datetime import datetime
import argparse, shutil
p=argparse.ArgumentParser()
p.add_argument('project', nargs='?', default='.')
p.add_argument('--apply',action='store_true')
a=p.parse_args()
root=Path(a.project).resolve()
if not (root/'docker-compose.yml').exists() or not (root/'backend'/'main.py').exists():
 raise SystemExit('Không thấy project hợp lệ (docker-compose.yml + backend/main.py).')
archive=root.parent/(root.name+'_cleanup_archive_'+datetime.now().strftime('%Y%m%d_%H%M%S'))
items=[]
# Files only generated by older patch installers. Keep original active files.
for base in [root,root/'backend',root/'backend'/'static']:
 if not base.exists():continue
 for f in base.glob('*.before_*'):
  if f.is_file():items.append(f)
# Unpacked installer folder was already applied by user. Keep only active code.
for name in ('EcomInsight_V7_ML2_Restore','EcomInsight_V6_Cleanup','EcomInsight_V5_Pink_Fix','ecom_ui_upgrade'):
 f=root/name
 if f.is_dir():items.append(f)
# Bytecode caches, rebuilt automatically
for base in (root/'backend',root/'app',root/'EcomInsight_V7_ML2_Restore'):
 if (base/'__pycache__').exists() and base/'__pycache__' not in items:items.append(base/'__pycache__')
if not items:
 print('Không có file backup/bản vá cũ thuộc danh sách an toàn.')
else:
 print(('SẼ CHUYỂN' if a.apply else 'XEM TRƯỚC')+' vào',archive)
 for f in items:
  rel=f.relative_to(root)
  print(' -',rel)
  if a.apply:
   dst=archive/rel;dst.parent.mkdir(parents=True,exist_ok=True)
   shutil.move(str(f),str(dst))
print('\nKHÔNG ĐỘNG ĐẾN: data/excel, data/news_seed, .env, SQL, app, dags, docker-compose, ml_outputs, outputs, notebooks, database.')
print('Không xóa docker-compose.api.yml/health.yml vì phải kiểm tra tham chiếu trước khi bỏ.')
print('Lệnh chạy thật: py .\\cleanup_project.py . --apply')
